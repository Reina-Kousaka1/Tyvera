use crate::diagnostic::Span;

#[derive(Clone, Debug, PartialEq)]
pub struct Token {
    pub kind: TokenKind,
    pub span: Span,
}

impl Token {
    pub fn new(kind: TokenKind, span: Span) -> Self {
        Self { kind, span }
    }
}

#[derive(Clone, Debug, PartialEq)]
pub enum TokenKind {
    Identifier(String),
    Integer(String),
    Float(String),
    String(String),

    Module,
    Import,
    As,
    Pub,
    Fn,
    Task,
    Struct,
    Enum,
    Type,
    Const,
    Let,
    Var,
    Return,
    If,
    Else,
    While,
    Spawn,
    Await,
    Chan,
    True,
    False,
    Nil,

    LParen,
    RParen,
    LBrace,
    RBrace,
    LBracket,
    RBracket,
    Comma,
    Colon,
    Semicolon,
    Dot,
    Question,
    Plus,
    Minus,
    Star,
    Slash,
    Percent,
    Bang,
    Equal,
    EqualEqual,
    BangEqual,
    Less,
    LessEqual,
    Greater,
    GreaterEqual,
    AndAnd,
    OrOr,
    Arrow,

    Eof,
}

impl TokenKind {
    pub fn label(&self) -> &'static str {
        match self {
            Self::Identifier(_) => "identifier",
            Self::Integer(_) => "integer",
            Self::Float(_) => "float",
            Self::String(_) => "string",
            Self::Module => "'module'",
            Self::Import => "'import'",
            Self::As => "'as'",
            Self::Pub => "'pub'",
            Self::Fn => "'fn'",
            Self::Task => "'task'",
            Self::Struct => "'struct'",
            Self::Enum => "'enum'",
            Self::Type => "'type'",
            Self::Const => "'const'",
            Self::Let => "'let'",
            Self::Var => "'var'",
            Self::Return => "'return'",
            Self::If => "'if'",
            Self::Else => "'else'",
            Self::While => "'while'",
            Self::Spawn => "'spawn'",
            Self::Await => "'await'",
            Self::Chan => "'chan'",
            Self::True => "'true'",
            Self::False => "'false'",
            Self::Nil => "'nil'",
            Self::LParen => "'('",
            Self::RParen => "')'",
            Self::LBrace => "'{'",
            Self::RBrace => "'}'",
            Self::LBracket => "'['",
            Self::RBracket => "']'",
            Self::Comma => "','",
            Self::Colon => "':'",
            Self::Semicolon => "';'",
            Self::Dot => "'.'",
            Self::Question => "'?'",
            Self::Plus => "'+'",
            Self::Minus => "'-'",
            Self::Star => "'*'",
            Self::Slash => "'/'",
            Self::Percent => "'%'",
            Self::Bang => "'!'",
            Self::Equal => "'='",
            Self::EqualEqual => "'=='",
            Self::BangEqual => "'!='",
            Self::Less => "'<'",
            Self::LessEqual => "'<='",
            Self::Greater => "'>'",
            Self::GreaterEqual => "'>='",
            Self::AndAnd => "'&&'",
            Self::OrOr => "'||'",
            Self::Arrow => "'->'",
            Self::Eof => "end of file",
        }
    }
}
